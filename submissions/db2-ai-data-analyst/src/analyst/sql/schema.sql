-- ---------------------------------------------------------------------
-- Business data: a small omni-channel retailer ("Northwind Bazaar")
-- ---------------------------------------------------------------------
CREATE TABLE {DATA}.REGIONS (
    REGION_ID    SMALLINT     NOT NULL PRIMARY KEY,
    REGION_NAME  VARCHAR(40)  NOT NULL,
    COUNTRY      VARCHAR(40)  NOT NULL
)@
COMMENT ON TABLE {DATA}.REGIONS IS 'Sales regions. Each store belongs to one region.'@

CREATE TABLE {DATA}.STORES (
    STORE_ID     INTEGER      NOT NULL PRIMARY KEY,
    STORE_NAME   VARCHAR(80)  NOT NULL,
    CITY         VARCHAR(60)  NOT NULL,
    REGION_ID    SMALLINT     NOT NULL REFERENCES {DATA}.REGIONS(REGION_ID),
    CHANNEL      VARCHAR(10)  NOT NULL CHECK (CHANNEL IN ('STORE','ONLINE')),
    OPENED_ON    DATE         NOT NULL
)@
COMMENT ON TABLE {DATA}.STORES IS 'Physical stores and the online web store (CHANNEL = ONLINE).'@
COMMENT ON COLUMN {DATA}.STORES.CHANNEL IS 'STORE for physical shops, ONLINE for e-commerce.'@
COMMENT ON COLUMN {DATA}.STORES.OPENED_ON IS 'Opening date. Stores opened after the data start have fewer trading days: compare revenue per trading day.'@

CREATE TABLE {DATA}.CUSTOMERS (
    CUSTOMER_ID  INTEGER      NOT NULL PRIMARY KEY,
    FULL_NAME    VARCHAR(80)  NOT NULL,
    EMAIL        VARCHAR(120) NOT NULL,
    CITY         VARCHAR(60)  NOT NULL,
    SEGMENT      VARCHAR(12)  NOT NULL CHECK (SEGMENT IN ('CONSUMER','SMB','ENTERPRISE')),
    LOYALTY_TIER VARCHAR(10)  NOT NULL CHECK (LOYALTY_TIER IN ('NONE','SILVER','GOLD','PLATINUM')),
    SIGNUP_DATE  DATE         NOT NULL
)@
COMMENT ON TABLE {DATA}.CUSTOMERS IS 'Registered customers. SEGMENT is CONSUMER, SMB or ENTERPRISE.'@
COMMENT ON COLUMN {DATA}.CUSTOMERS.LOYALTY_TIER IS 'NONE, SILVER, GOLD or PLATINUM (highest).'@

CREATE TABLE {DATA}.PRODUCTS (
    PRODUCT_ID   INTEGER       NOT NULL PRIMARY KEY,
    SKU          VARCHAR(20)   NOT NULL UNIQUE,
    PRODUCT_NAME VARCHAR(100)  NOT NULL,
    CATEGORY     VARCHAR(40)   NOT NULL,
    SUBCATEGORY  VARCHAR(40)   NOT NULL,
    BRAND        VARCHAR(40)   NOT NULL,
    UNIT_COST    DECIMAL(10,2) NOT NULL,
    LIST_PRICE   DECIMAL(10,2) NOT NULL
)@
COMMENT ON TABLE {DATA}.PRODUCTS IS 'Product catalogue. Margin per unit = LIST_PRICE - UNIT_COST.'@

CREATE TABLE {DATA}.ORDERS (
    ORDER_ID     INTEGER       NOT NULL PRIMARY KEY,
    CUSTOMER_ID  INTEGER       NOT NULL REFERENCES {DATA}.CUSTOMERS(CUSTOMER_ID),
    STORE_ID     INTEGER       NOT NULL REFERENCES {DATA}.STORES(STORE_ID),
    ORDER_DATE   DATE          NOT NULL,
    STATUS       VARCHAR(10)   NOT NULL CHECK (STATUS IN ('COMPLETED','RETURNED','CANCELLED')),
    PAYMENT      VARCHAR(12)   NOT NULL,
    SHIPPING_FEE DECIMAL(8,2)  NOT NULL DEFAULT 0
)@
COMMENT ON TABLE {DATA}.ORDERS IS 'Order headers. Revenue should normally only count STATUS = COMPLETED.'@
COMMENT ON COLUMN {DATA}.ORDERS.PAYMENT IS 'CARD, UPI, WALLET, COD or INVOICE.'@

CREATE TABLE {DATA}.ORDER_ITEMS (
    ORDER_ID     INTEGER       NOT NULL REFERENCES {DATA}.ORDERS(ORDER_ID),
    LINE_NO      SMALLINT      NOT NULL,
    PRODUCT_ID   INTEGER       NOT NULL REFERENCES {DATA}.PRODUCTS(PRODUCT_ID),
    QUANTITY     SMALLINT      NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE   DECIMAL(10,2) NOT NULL,
    DISCOUNT_PCT DECIMAL(4,2)  NOT NULL DEFAULT 0,
    PRIMARY KEY (ORDER_ID, LINE_NO)
)@
COMMENT ON TABLE {DATA}.ORDER_ITEMS IS 'Order lines. Line revenue = QUANTITY * UNIT_PRICE * (100 - DISCOUNT_PCT) / 100.'@

CREATE INDEX {DATA}.IX_ORDERS_DATE     ON {DATA}.ORDERS (ORDER_DATE, STATUS)@
CREATE INDEX {DATA}.IX_ORDERS_CUSTOMER ON {DATA}.ORDERS (CUSTOMER_ID)@
CREATE INDEX {DATA}.IX_ORDERS_STORE    ON {DATA}.ORDERS (STORE_ID)@
CREATE INDEX {DATA}.IX_ITEMS_PRODUCT   ON {DATA}.ORDER_ITEMS (PRODUCT_ID)@
CREATE INDEX {DATA}.IX_PRODUCTS_CAT    ON {DATA}.PRODUCTS (CATEGORY, SUBCATEGORY)@

-- Convenience view the LLM can use for most revenue questions.
CREATE OR REPLACE VIEW {DATA}.V_SALES AS
SELECT o.ORDER_ID, i.LINE_NO, o.ORDER_DATE, o.STATUS, o.CUSTOMER_ID, o.STORE_ID,
       s.CHANNEL, r.REGION_NAME, p.PRODUCT_ID, p.CATEGORY, p.SUBCATEGORY, p.BRAND,
       i.QUANTITY,
       -- (100 - pct) / 100 keeps Db2 decimal precision bounded (pct / 100 alone overflows on SUM).
       DECIMAL(i.QUANTITY * i.UNIT_PRICE * (100 - i.DISCOUNT_PCT) / 100, 12, 2) AS NET_REVENUE,
       DECIMAL(i.QUANTITY * (i.UNIT_PRICE * (100 - i.DISCOUNT_PCT) / 100 - p.UNIT_COST), 12, 2) AS GROSS_PROFIT
FROM {DATA}.ORDERS o
JOIN {DATA}.ORDER_ITEMS i ON i.ORDER_ID = o.ORDER_ID
JOIN {DATA}.PRODUCTS p    ON p.PRODUCT_ID = i.PRODUCT_ID
JOIN {DATA}.STORES s      ON s.STORE_ID = o.STORE_ID
JOIN {DATA}.REGIONS r     ON r.REGION_ID = s.REGION_ID@
COMMENT ON TABLE {DATA}.V_SALES IS 'One row per order line (grain: ORDER_ID, LINE_NO) with net revenue and gross profit already computed. Prefer this view for sales questions; filter STATUS = ''COMPLETED'' for revenue.'@

-- ---------------------------------------------------------------------
-- Voice of the customer: social media / review posts about our products
-- and stores. Embeddings live in {APP}.SOCIAL_EMBEDDINGS (not visible to the
-- query user); semantic search joins the two in a single Db2 statement.
-- ---------------------------------------------------------------------
CREATE TABLE {DATA}.SOCIAL_POSTS (
    POST_ID      INTEGER       NOT NULL PRIMARY KEY,
    EXTERNAL_ID  VARCHAR(80)   NOT NULL UNIQUE,
    PLATFORM     VARCHAR(10)   NOT NULL CHECK (PLATFORM IN ('REDDIT','X','REVIEW','OTHER')),
    CHANNEL      VARCHAR(80)   NOT NULL,
    AUTHOR       VARCHAR(80)   NOT NULL,
    POSTED_AT    TIMESTAMP     NOT NULL,
    POST_DATE    DATE          NOT NULL,
    PRODUCT_ID   INTEGER       REFERENCES {DATA}.PRODUCTS(PRODUCT_ID),
    STORE_ID     INTEGER       REFERENCES {DATA}.STORES(STORE_ID),
    BRAND        VARCHAR(40),
    TOPIC        VARCHAR(20)   NOT NULL,
    SENTIMENT    DECIMAL(4,3)  NOT NULL CHECK (SENTIMENT BETWEEN -1 AND 1),
    ENGAGEMENT   INTEGER       NOT NULL DEFAULT 0,
    POST_TEXT    VARCHAR(1000) NOT NULL,
    URL          VARCHAR(300)
)@
COMMENT ON TABLE {DATA}.SOCIAL_POSTS IS 'Customer posts from Reddit, X and review sites mentioning our products, brands or stores. One row per post.'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.PLATFORM IS 'REDDIT, X, REVIEW (product review sites) or OTHER.'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.CHANNEL IS 'Subreddit (r/...), X handle or review site the post came from.'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.PRODUCT_ID IS 'Product the post is about, when it names one (nullable).'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.STORE_ID IS 'Store the post is about, when it names one (nullable).'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.TOPIC IS 'QUALITY, DELIVERY, PRICE, SERVICE, STORE, SIZING, APP or PRAISE.'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.SENTIMENT IS 'Sentiment score from -1 (very negative) to +1 (very positive).'@
COMMENT ON COLUMN {DATA}.SOCIAL_POSTS.ENGAGEMENT IS 'Likes + replies/upvotes at collection time.'@
CREATE INDEX {DATA}.IX_SOCIAL_DATE    ON {DATA}.SOCIAL_POSTS (POST_DATE, PLATFORM)@
CREATE INDEX {DATA}.IX_SOCIAL_PRODUCT ON {DATA}.SOCIAL_POSTS (PRODUCT_ID)@

-- ---------------------------------------------------------------------
-- Application schema: semantic query memory + audit trail
-- ---------------------------------------------------------------------
CREATE TABLE {APP}.QUERY_MEMORY (
    MEMORY_ID    INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    QUESTION     VARCHAR(1000) NOT NULL,
    SQL_TEXT     CLOB(64K)     NOT NULL,
    EMBEDDING    VECTOR({DIM}, FLOAT32) NOT NULL,
    SOURCE       VARCHAR(10)   NOT NULL DEFAULT 'SEED' CHECK (SOURCE IN ('SEED','USER')),
    TIMES_USED   INTEGER       NOT NULL DEFAULT 0,
    CREATED_AT   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP
)@
COMMENT ON TABLE {APP}.QUERY_MEMORY IS 'Verified question -> SQL pairs with Gemini embeddings, retrieved by VECTOR_DISTANCE as few-shot examples.'@

CREATE TABLE {APP}.SOCIAL_EMBEDDINGS (
    POST_ID      INTEGER       NOT NULL PRIMARY KEY REFERENCES {DATA}.SOCIAL_POSTS(POST_ID) ON DELETE CASCADE,
    EMBEDDING    VECTOR({DIM}, FLOAT32) NOT NULL
)@
COMMENT ON TABLE {APP}.SOCIAL_EMBEDDINGS IS 'Gemini embeddings of SOCIAL_POSTS.POST_TEXT for semantic (VECTOR_DISTANCE) search.'@

CREATE TABLE {APP}.QUERY_AUDIT (
    AUDIT_ID     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ASKED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    QUESTION     VARCHAR(1000) NOT NULL,
    SQL_TEXT     CLOB(64K),
    STATUS       VARCHAR(12)   NOT NULL,
    EST_COST     DOUBLE,
    ROW_COUNT    INTEGER,
    ELAPSED_MS   INTEGER,
    ATTEMPTS     SMALLINT      NOT NULL DEFAULT 1,
    ERROR_TEXT   VARCHAR(2000),
    DETAILS      CLOB(1M)
)@
COMMENT ON TABLE {APP}.QUERY_AUDIT IS 'Every question asked, the SQL executed, optimizer cost, outcome and timing.'@
CREATE INDEX {APP}.IX_AUDIT_TIME ON {APP}.QUERY_AUDIT (ASKED_AT DESC)@

-- Stored procedure used by the app to write the audit trail.
CREATE OR REPLACE PROCEDURE {APP}.LOG_QUERY (
    IN  P_QUESTION VARCHAR(1000),
    IN  P_SQL      CLOB(64K),
    IN  P_STATUS   VARCHAR(12),
    IN  P_COST     DOUBLE,
    IN  P_ROWS     INTEGER,
    IN  P_MS       INTEGER,
    IN  P_ATTEMPTS SMALLINT,
    IN  P_ERROR    VARCHAR(2000),
    IN  P_DETAILS  CLOB(1M),
    OUT P_AUDIT_ID BIGINT
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
    INSERT INTO {APP}.QUERY_AUDIT
        (QUESTION, SQL_TEXT, STATUS, EST_COST, ROW_COUNT, ELAPSED_MS, ATTEMPTS, ERROR_TEXT, DETAILS)
    VALUES
        (P_QUESTION, P_SQL, P_STATUS, P_COST, P_ROWS, P_MS, P_ATTEMPTS, P_ERROR, P_DETAILS);
    SET P_AUDIT_ID = IDENTITY_VAL_LOCAL();
END@

-- Usage analytics view for the dashboard.
CREATE VIEW {APP}.V_AUDIT_DAILY AS
SELECT DATE(ASKED_AT) AS DAY,
       COUNT(*) AS QUESTIONS,
       SUM(CASE WHEN STATUS = 'OK' THEN 1 ELSE 0 END) AS SUCCEEDED,
       SUM(CASE WHEN STATUS = 'BLOCKED' THEN 1 ELSE 0 END) AS BLOCKED,
       AVG(ELAPSED_MS) AS AVG_MS
FROM {APP}.QUERY_AUDIT
GROUP BY DATE(ASKED_AT)@
